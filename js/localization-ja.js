const JAPANESE_TEXT_PATTERN = new RegExp(
  Object.keys(JAPANESE_TEXT).filter(text=>text.length>1)
    .sort((left,right)=>right.length-left.length)
    .map(text=>text.replace(/[.*+?^${}()|[\]\\]/g,'\\$&'))
    .join('|'),
  'g'
);
const JAPANESE_TEXT_CACHE = new Map();

function localizeGameText(value){
  const text=String(value);
  if(typeof gameLanguage==='undefined'||gameLanguage!=='ja')return text;
  if(JAPANESE_TEXT_CACHE.has(text))return JAPANESE_TEXT_CACHE.get(text);
  if(/[\u3040-\u30ff]/.test(text))return text;
  const localized=Object.prototype.hasOwnProperty.call(JAPANESE_TEXT,text)
    ?JAPANESE_TEXT[text]
    :text.replace(JAPANESE_TEXT_PATTERN,match=>JAPANESE_TEXT[match]);
  if(JAPANESE_TEXT_CACHE.size>=2048)JAPANESE_TEXT_CACHE.delete(JAPANESE_TEXT_CACHE.keys().next().value);
  JAPANESE_TEXT_CACHE.set(text,localized);
  return localized;
}

